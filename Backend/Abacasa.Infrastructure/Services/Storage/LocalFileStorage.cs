using Abacasa.Application.Interfaces;
using Abacasa.Infrastructure.Configuration;

namespace Abacasa.Infrastructure.Services.Storage
{
    /// <summary>Stores files on the server disk; Program.cs serves the folder at Storage:Local:RequestPath.</summary>
    public class LocalFileStorage : IFileStorage
    {
        private readonly string _root;
        private readonly string _requestPath;

        /// <summary>Absolute folder and URL path, used by Program.cs to serve the files.</summary>
        public string RootPath => _root;
        public string RequestPath => _requestPath;

        public LocalFileStorage(string rootPath, LocalStorageSettings settings)
        {
            _root = Path.GetFullPath(rootPath);
            _requestPath = "/" + settings.RequestPath.Trim('/');
            Directory.CreateDirectory(_root);
        }

        public async Task SaveAsync(string key, Stream content, string contentType, CancellationToken cancellationToken = default)
        {
            var path = ResolvePath(key);
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);

            // Write to a temp file first so a half-written file is never served
            var tempPath = path + ".tmp";
            await using (var file = new FileStream(tempPath, FileMode.Create, FileAccess.Write, FileShare.None))
            {
                await content.CopyToAsync(file, cancellationToken);
            }
            File.Move(tempPath, path, overwrite: true);
        }

        public Task DeleteAsync(string key, CancellationToken cancellationToken = default)
        {
            var path = ResolvePath(key);
            if (File.Exists(path))
                File.Delete(path);
            return Task.CompletedTask;
        }

        public string GetPublicUrl(string key) => $"{_requestPath}/{key}";

        // Keys are generated by the server, but never let one escape the storage root
        private string ResolvePath(string key)
        {
            var path = Path.GetFullPath(Path.Combine(_root, key));
            if (!path.StartsWith(_root + Path.DirectorySeparatorChar, StringComparison.Ordinal))
                throw new ArgumentException($"Invalid storage key '{key}'.", nameof(key));
            return path;
        }
    }
}
